def main() -> None:
    existing: dict[str, dict[str, str]] = {}
    if OUT.exists():
        with OUT.open("r", encoding="utf-8-sig", newline="") as f:
            for row in csv.DictReader(f):
                existing[row["region_code"]] = row

    for code, name, level, parent in ROWS:
        existing[code] = {
            "region_code": code,
            "name": name,
            "short_name": "",
            "level": level,
            "parent_code": parent,
            "aliases": existing.get(code, {}).get("aliases", ""),
        }

    fields = ["region_code", "name", "short_name", "level", "parent_code", "aliases"]
    with OUT.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        for code in sorted(existing):
            w.writerow(existing[code])
    print(f"region rows={len(existing)} -> {OUT}")


if __name__ == "__main__":
    main()
