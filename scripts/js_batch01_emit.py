def write_csv(path: Path, cols: list[str], rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols, extrasaction="ignore")
        w.writeheader()
        for r in rows:
            w.writerow({c: r.get(c, "") for c in cols})


def save_raw(slug: str, url: str, title: str, publisher: str, published_ymd: str,
             excerpt: str, cred: str) -> tuple[str, str]:
    d = RAW / f"{TODAY}-{slug}"
    d.mkdir(parents=True, exist_ok=True)
    md = d / "原文.md"
    body = f"# {title}\n\n- URL: {url}\n- 发布者: {publisher}\n- 发布日期: {published_ymd}\n- 抓取时间: {FETCHED}\n- 可信度: {cred}\n\n## 正文摘录\n\n{excerpt}\n"
    md.write_text(body, encoding="utf-8")
    h = hashlib.sha256(body.encode("utf-8")).hexdigest()
    meta = {
        "url": url, "title": title, "publisher": publisher,
        "published_ymd": published_ymd, "fetched_at": FETCHED, "cred": cred,
        "hash_sha256": h,
    }
    (d / "meta.json").write_text(json.dumps(meta, ensure_ascii=False, indent=2), encoding="utf-8")
    return f"data/raw/JS/{TODAY}-{slug}/原文.md", h


